export interface DemoCriterion {
  title: string;
  maxScore: number;
}

export interface DemoAssignment {
  title: string;
  topic: string;
  goal: string;
  instruction: string;
  difficulty: DifficultyLevel;
  type: string;
  formats: SubmissionFormat[];
  criteria: DemoCriterion[];
  /** Этап ИОТ (0–4), к которому относится задание; null — только в библиотеке. */
  stage: number | null;
}

/** Критерии задания: сумма баллов — шкала задания (ASSIGNMENT_SCORE_MAX = 100). */
const criteria = (...items: [string, number][]): DemoCriterion[] =>
  items.map(([title, maxScore]) => ({ title, maxScore }));

/** Три уровня сложности задания для этапа: базовый, средний, повышенный. */
function stageSet(
  stage: number,
  topic: string,
  type: string,
  items: [string, string, string][],
): DemoAssignment[] {
  const levels: DifficultyLevel[] = ['BASIC', 'INTERMEDIATE', 'ADVANCED'];
  return items.map(([title, goal, instruction], index) => ({
    title,
    topic,
    goal,
    instruction,
    difficulty: levels[index]!,
    type,
    formats: ['TEXT', 'FILE', 'LINK'],
    criteria:
      index === 0
        ? criteria(['Правильность решения', 60], ['Оформление', 40])
        : criteria(
            ['Правильность решения', 50],
            ['Обоснование хода решения', 30],
            ['Оформление', 20],
          ),
    stage,
  }));
}

